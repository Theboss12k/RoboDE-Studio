// Generate TypeScript types from contracts/schemas/*.json into packages/core/src/generated/types.ts.
//   node scripts/contracts-types.mjs           write the file
//   node scripts/contracts-types.mjs --check   exit 1 when the committed file is stale
// Every schema repeats the shared $defs, so they are merged into one document and compiled once.
import { compile } from "json-schema-to-typescript";
import { readdirSync, readFileSync, writeFileSync, mkdirSync, mkdtempSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "contracts", "schemas");
const target = join(root, "packages", "core", "src", "generated", "types.ts");

// The server serialises models with every field, so a field that has a default is always present in responses: mark it
// required. Property-level titles ("Version", "Created") would become noisy type aliases: drop them.
function normalise(node, top = true) {
  if (Array.isArray(node)) return node.map((n) => normalise(n, false));
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "title" && !top) continue;
    if (k === "x-optional") continue;  // marker only, consumed below
    if (k === "default") continue;  // differing defaults would split one model into BasePose / BasePose1
    if (k === "prefixItems") { out.items = normalise(v, false); continue; }  // 2020-12 tuple -> draft-07 tuple
    if (k === "properties") out[k] = Object.fromEntries(Object.entries(v).map(([n, s]) => [n, normalise(s, false)]));
    else out[k] = normalise(v, false);
  }
  if (out.properties && out.type === "object") {
    // fields marked x-optional (absent from older stored versions) stay optional
    out.required = Object.keys(out.properties).filter((n) => !(node.properties[n] && node.properties[n]["x-optional"]));
  }
  return out;
}

const defs = {};
const roots = [];
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".json")).sort()) {
  const { $defs = {}, ...schema } = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  for (const [k, v] of Object.entries($defs)) defs[k] = normalise(v);
  const name = schema.title || file.replace(/\.json$/, "");
  defs[name] = normalise(schema);
  roots.push(name);
}
const combined = {
  title: "Contracts", type: "object", additionalProperties: false,
  properties: Object.fromEntries(roots.map((n) => [n, { $ref: `#/$defs/${n}` }])), $defs: defs,
};
const banner = "/* eslint-disable */\n// Generated by scripts/contracts-types.mjs from contracts/schemas/*.json. Do not edit; run `npm run contracts:types`.\n";
const text = await compile(combined, "Contracts", { bannerComment: banner, additionalProperties: false, format: true, unreachableDefinitions: true });

if (process.argv.includes("--check")) {
  const dir = mkdtempSync(join(tmpdir(), "contracts-"));
  const tmp = join(dir, "types.ts");
  writeFileSync(tmp, text);
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
    console.error("packages/core/src/generated/types.ts is stale. Run `npm run contracts:types`.");
    process.exit(1);
  }
  console.log("contracts types are up to date");
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
  console.log(`wrote ${target}`);
}
