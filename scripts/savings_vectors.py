"""Shared test vectors for the time-saved formulas (server/studio/physics/savings.py and packages/core/src/savings.ts).

    .venv/bin/python scripts/savings_vectors.py          # rewrite contracts/savings_vectors.json
    .venv/bin/python scripts/savings_vectors.py --check  # exit 1 when the committed file is stale

The TS side (`node scripts/savings-parity.mjs`) replays every vector and compares with the stored Python results.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'server'))

from studio.physics import savings as sv  # noqa: E402
from studio.schemas import Baseline  # noqa: E402

OUT = ROOT / 'contracts' / 'savings_vectors.json'

BASE = dict(robot_cycle_s=6.0, manual_cycle_s=15.0, operators=1, shifts_per_day=1.0, hours_per_shift=8.0,
            days_per_week=5.0, days_per_year=250.0, supervision_min_per_shift=15.0)


def build():
    cases = [('defaults', {}),
             ('slow robot, two operators', dict(robot_cycle_s=20.0, manual_cycle_s=12.5, operators=2)),
             ('two shifts, six days', dict(robot_cycle_s=7.3, manual_cycle_s=41.0, operators=3, shifts_per_day=2.0,
                                           days_per_week=6.0, days_per_year=300.0)),
             ('fractional shift, no supervision', dict(robot_cycle_s=3.3, manual_cycle_s=9.9, shifts_per_day=0.5,
                                                       hours_per_shift=7.5, supervision_min_per_shift=0.0)),
             ('robot slower than the people', dict(robot_cycle_s=30.0, manual_cycle_s=10.0, operators=4))]
    sav = []
    for name, over in cases:
        inputs = {**BASE, **over}
        sav.append(dict(name=name, inputs=inputs, expected=sv.savings(inputs).model_dump(mode='json')))
    base = lambda src, m=20.0, o=2: Baseline(manual_cycle_s=m, operators=o, source=src).model_dump(mode='json')  # noqa: E731
    resolve = []
    for name, baseline, over in (('no baseline', None, None),
                                 ('estimate baseline', base('estimate'), None),
                                 ('user baseline', base('user'), None),
                                 ('override of manual time on an estimate', base('estimate'), dict(manual_cycle_s=33.0)),
                                 ('override of operators only', None, dict(operators=4)),
                                 ('empty overrides', base('estimate'), {}),
                                 ('zero overrides are ignored', base('estimate'), dict(manual_cycle_s=0, operators=0))):
        b = Baseline.model_validate(baseline) if baseline else None
        resolve.append(dict(name=name, baseline=baseline, overrides=over, expected=sv.resolve_baseline(b, over)))
    return dict(version=1, note='Generated by scripts/savings_vectors.py; do not edit.', savings=sav, resolve=resolve)


def render():
    return json.dumps(build(), indent=1) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('contracts/savings_vectors.json is stale: run .venv/bin/python scripts/savings_vectors.py')
            sys.exit(1)
        print('contracts/savings_vectors.json is up to date')
    else:
        OUT.write_text(text)
        print(f'wrote {OUT.relative_to(ROOT)}')
